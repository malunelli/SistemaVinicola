    private Bebida obterBebidaSelecionada() {
        if (cmbBebida.getSelectedItem() == null) {
            return null;
        }

        String nome = cmbBebida.getSelectedItem().toString();

        for (Bebida b : BDBebida.getInstancia().getBebidas()) {
            if (b.getNome().equalsIgnoreCase(nome)) {
                return b;
            }
        }

        return null;
    }
    
    private Vendedor obterVendedorSelecionado() {
        if (cmbVendedor.getSelectedItem() == null) {
            return null;
        }

        String nome = cmbVendedor.getSelectedItem().toString();

        for (Vendedor v : BDVendedor.getInstancia().getVendedores()) {
            if (v.getNome().equalsIgnoreCase(nome)) {
                return v;
            }
        }

        return null;
    }
    
