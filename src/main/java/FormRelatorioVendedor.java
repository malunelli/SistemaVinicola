   private Vendedor obterVendedorSelecionado() {
        int linha = tblVendedores.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um vendedor na tabela.");
            return null;
        }

        String cpf = tblVendedores.getValueAt(linha, 0).toString();

        return BDVendedor.getInstancia().consultarVendedorPorCpf(cpf);
    }

    private void alterarVendedor() {
        Vendedor vendedor = obterVendedorSelecionado();

        if (vendedor == null) {
            return;
        }

        FormCadastroVendedor tela = FormCadastroVendedor.getInstancia();
        tela.prepararParaEdicao(vendedor);
        tela.setLocationRelativeTo(this);
        tela.setVisible(true);
    }

    private void excluirVendedor() {
        Vendedor vendedor = obterVendedorSelecionado();

        if (vendedor == null) {
            return;
        }

        int opcao = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir o vendedor " + vendedor.getNome() + "?",
                "Confirmar exclusao",
                JOptionPane.YES_NO_OPTION
        );

        if (opcao == JOptionPane.YES_OPTION) {
            boolean excluiu = BDVendedor.getInstancia().excluirVendedor(vendedor.getCpf());

            if (excluiu) {
                JOptionPane.showMessageDialog(this, "Vendedor excluido com sucesso!");
                preencherTabela();
            } else {
                JOptionPane.showMessageDialog(this, "Vendedor nao encontrado.");
            }
        }
    }

    private void mostrarDetalhes() {
        Vendedor vendedor = obterVendedorSelecionado();

        if (vendedor == null) {
            return;
        }

        String mensagem = "";

        mensagem += "CPF: " + vendedor.getCpf() + "\n";
        mensagem += "Nome: " + vendedor.getNome() + "\n";
        mensagem += "Resumo: " + vendedor.gerarResumo() + "\n";
        mensagem += "Telefone: " + vendedor.getTelefone() + "\n";
        mensagem += "Email: " + vendedor.getEmail() + "\n";
        mensagem += "Data de Nascimento: " + vendedor.getDataNascimento() + "\n";
        mensagem += "Matricula: " + vendedor.getMatricula() + "\n";
        mensagem += "Salario Base: R$ " + String.format("%.2f", vendedor.getSalarioBase()) + "\n";
        mensagem += "Comissao: " + String.format("%.2f", vendedor.getPercentualComissao()) + "%\n";

        JOptionPane.showMessageDialog(this, mensagem, "Detalhes do Vendedor", JOptionPane.INFORMATION_MESSAGE);
    }

    public void preencherTabela() {
        DefaultTableModel modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        modelo.addColumn("CPF");
        modelo.addColumn("Nome");
        modelo.addColumn("Matricula");
        modelo.addColumn("Comissao");

        for (Vendedor v : BDVendedor.getInstancia().getVendedores()) {
            modelo.addRow(new Object[]{
                v.getCpf(),
                v.getNome(),
                v.getMatricula(),
                String.format("%.2f", v.getPercentualComissao())
            });
        }

        tblVendedores.setModel(modelo);
        personalizarTabela();
    }

    private void atualizar() {
        preencherTabela();
    }

