    public void preencherFormulario(Cliente c) {
        txtCpf.setText(c.getCpf());
        txtCpf.setEditable(false);
        txtNome.setText(c.getNome());
        txtTelefone.setText(c.getTelefone());
        txtEmail.setText(c.getEmail());
        txtDataNasc.setText(c.getDataNascimento());
        txtEndereco.setText(c.getEnderecoEntrega());
        txtLimite.setText(String.valueOf(c.getLimiteCredito()));
    }

    private void salvarCliente() {
        try {
            boolean estavaEditando = clienteEmEdicao != null;

            String cpf = txtCpf.getText();
            String nome = txtNome.getText();
            String telefone = txtTelefone.getText();
            String email = txtEmail.getText();
            String dataNasc = txtDataNasc.getText();
            String endereco = txtEndereco.getText();
            double limite = Double.parseDouble(txtLimite.getText());

            if (clienteEmEdicao == null) {
                Cliente cliente = new Cliente();

                cliente.setCpf(cpf);
                cliente.setNome(nome);
                cliente.setTelefone(telefone);
                cliente.setEmail(email);
                cliente.setDataNascimento(dataNasc);
                cliente.setEnderecoEntrega(endereco);
                cliente.setLimiteCredito(limite);

                BDCliente.getInstancia().adicionarCliente(cliente);

                JOptionPane.showMessageDialog(this, "Cliente cadastrado com sucesso!");
            } else {
                clienteEmEdicao.setNome(nome);
                clienteEmEdicao.setTelefone(telefone);
                clienteEmEdicao.setEmail(email);
                clienteEmEdicao.setDataNascimento(dataNasc);
                clienteEmEdicao.setEnderecoEntrega(endereco);
                clienteEmEdicao.setLimiteCredito(limite);

                BDCliente.getInstancia().alterarCliente(cpf, clienteEmEdicao);

                JOptionPane.showMessageDialog(this, "Cliente alterado com sucesso!");
            }

            limparCampos();

            if (estavaEditando) {
                fechar();
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Erro: o limite de crédito deve ser um número válido.");
        } catch (CpfInvalidoException e) {
            JOptionPane.showMessageDialog(this, "Erro no CPF: " + e.getMessage());
        } catch (LimiteInvalidoException e) {
            JOptionPane.showMessageDialog(this, "Erro no limite de crédito: " + e.getMessage());
        }
    }
    public void prepararParaEdicao(Cliente c) {
        clienteEmEdicao = c;
        preencherFormulario(c);
    }

    public void limparCampos() {
        clienteEmEdicao = null;

        txtCpf.setText("");
        txtCpf.setEditable(true);
        txtNome.setText("");
        txtTelefone.setText("");
        txtEmail.setText("");
        txtDataNasc.setText("");
        txtEndereco.setText("");
        txtLimite.setText("");

        txtCpf.requestFocus();
    }

    public void fechar() {
        this.dispose();
    }
