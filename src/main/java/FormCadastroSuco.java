    private void salvarSuco() {
        try {
            String nome = txtNome.getText();
            if (BDBebida.getInstancia().consultarBebidaPorNome(nome) != null) {
                JOptionPane.showMessageDialog(this, "Ja existe uma bebida cadastrada com esse nome.");
                return;
            }
            int volume = Integer.parseInt(txtVolume.getText());
            double preco = Double.parseDouble(txtPreco.getText());
            double teorFruta = Double.parseDouble(txtTeorFruta.getText());

            boolean contemConservante = cmbConservante.getSelectedItem().toString().equalsIgnoreCase("Sim");

            Suco suco = new Suco();

            suco.setNome(nome);
            suco.setVolumeMl(volume);
            suco.setPrecoBase(preco);
            suco.setTeorFruta(teorFruta);
            suco.setContemConservante(contemConservante);

            BDBebida.getInstancia().adicionarBebida(suco);

            JOptionPane.showMessageDialog(this, "Suco cadastrado com sucesso!");

            limparCampos();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Erro: volume, preço e teor de fruta devem ser números válidos.");
        } catch (PrecoInvalidoException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        } catch (VolumeInvalidoException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }

    public void limparCampos() {
        txtNome.setText("");
        txtVolume.setText("");
        txtPreco.setText("");
        txtTeorFruta.setText("");
        cmbConservante.setSelectedIndex(0);
        txtNome.requestFocus();
    }

    private void fechar() {
        this.dispose();
    }
    
