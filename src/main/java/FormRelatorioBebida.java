    private void alterarBebida() {
        Bebida b = obterBebidaSelecionada();

        if (b == null) {
            return;
        }

        try {
            String novoNome = JOptionPane.showInputDialog(this, "Novo nome:", b.getNome());
            String novoVolume = JOptionPane.showInputDialog(this, "Novo volume ml:", b.getVolumeMl());
            String novoPreco = JOptionPane.showInputDialog(this, "Novo preco base:", b.getPrecoBase());

            if (novoNome == null || novoVolume == null || novoPreco == null) {
                return;
            }
            
            Bebida bebidaMesmoNome = BDBebida.getInstancia().consultarBebidaPorNome(novoNome);

            if (bebidaMesmoNome != null && bebidaMesmoNome != b) {
                JOptionPane.showMessageDialog(this, "Ja existe outra bebida cadastrada com esse nome.");
                return;
            }
            b.setNome(novoNome);
            b.setVolumeMl(Integer.parseInt(novoVolume));
            b.setPrecoBase(Double.parseDouble(novoPreco));

            if (b instanceof Vinho) {
                Vinho v = (Vinho) b;

                String novoTipoUva = JOptionPane.showInputDialog(this, "Novo tipo da uva:", v.getTipoUva());
                String novoAnoSafra = JOptionPane.showInputDialog(this, "Novo ano da safra:", v.getAnoSafra());

                if (novoTipoUva == null || novoAnoSafra == null) {
                    return;
                }

                v.setTipoUva(novoTipoUva);
                v.setAnoSafra(Integer.parseInt(novoAnoSafra));

            } else if (b instanceof Suco) {
                Suco s = (Suco) b;

                String novoTeorFruta = JOptionPane.showInputDialog(this, "Novo teor de fruta:", s.getTeorFruta());
                String novoConservante = JOptionPane.showInputDialog(this, "Contem conservante? Sim/Nao:", s.isContemConservante() ? "Sim" : "Nao");

                if (novoTeorFruta == null || novoConservante == null) {
                    return;
                }

                s.setTeorFruta(Double.parseDouble(novoTeorFruta));
                s.setContemConservante(novoConservante.equalsIgnoreCase("Sim"));

            } else if (b instanceof Espumante) {
                Espumante e = (Espumante) b;

                String novoTipoFermentacao = JOptionPane.showInputDialog(this, "Novo tipo de fermentacao:", e.getTipoFermentacao());
                String novoPrecoAdicional = JOptionPane.showInputDialog(this, "Novo preco adicional brut:", e.getPrecoAdicionalBrut());

                if (novoTipoFermentacao == null || novoPrecoAdicional == null) {
                    return;
                }

                e.setTipoFermentacao(novoTipoFermentacao);
                e.setPrecoAdicionalBrut(Double.parseDouble(novoPrecoAdicional));
            }

            JOptionPane.showMessageDialog(this, "Bebida alterada com sucesso!");
            preencherTabela();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Erro: confira os campos numericos.");
        } catch (PrecoInvalidoException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        } catch (VolumeInvalidoException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }
    
    private void excluirBebida() {
        Bebida b = obterBebidaSelecionada();

        if (b == null) {
            return;
        }

        int opcao = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir a bebida " + b.getNome() + "?",
                "Confirmar exclusao",
                JOptionPane.YES_NO_OPTION
        );

        if (opcao == JOptionPane.YES_OPTION) {
            boolean excluiu = BDBebida.getInstancia().excluirBebida(b.getNome());

            if (excluiu) {
                JOptionPane.showMessageDialog(this, "Bebida excluida com sucesso!");
                preencherTabela();
            } else {
                JOptionPane.showMessageDialog(this, "Bebida nao encontrada.");
            }
        }
    }
    
    private void mostrarDetalhes() {
        Bebida b = obterBebidaSelecionada();

        if (b == null) {
            return;
        }

        String mensagem = "";

        mensagem += "Nome: " + b.getNome() + "\n";
        mensagem += "Tipo: " + identificarTipo(b) + "\n";
        mensagem += "Volume: " + b.getVolumeMl() + " ml\n";
        mensagem += "Preco Base: R$ " + String.format("%.2f", b.getPrecoBase()) + "\n";
        mensagem += "Preco Final: R$ " + String.format("%.2f", b.calcularPrecoFinal()) + "\n";
        mensagem += "Categoria: " + b.definirCategoria() + "\n";

        if (b instanceof Vinho) {
            Vinho v = (Vinho) b;
            mensagem += "Tipo da Uva: " + v.getTipoUva() + "\n";
            mensagem += "Ano da Safra: " + v.getAnoSafra() + "\n";
        } else if (b instanceof Suco) {
            Suco s = (Suco) b;
            mensagem += "Teor de Fruta: " + s.getTeorFruta() + "\n";
            mensagem += "Contem Conservante: " + (s.isContemConservante() ? "Sim" : "Nao") + "\n";
        } else if (b instanceof Espumante) {
            Espumante e = (Espumante) b;
            mensagem += "Tipo de Fermentacao: " + e.getTipoFermentacao() + "\n";
            mensagem += "Preco Adicional Brut: R$ " + String.format("%.2f", e.getPrecoAdicionalBrut()) + "\n";
        }

        JOptionPane.showMessageDialog(this, mensagem, "Detalhes da Bebida", JOptionPane.INFORMATION_MESSAGE);
    }

    public void preencherTabela() {
        DefaultTableModel modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        modelo.addColumn("Nome");
        modelo.addColumn("Tipo");
        modelo.addColumn("Volume ml");
        modelo.addColumn("Preco Final");

        for (Bebida b : BDBebida.getInstancia().getBebidas()) {
            modelo.addRow(new Object[]{
                b.getNome(),
                identificarTipo(b),
                b.getVolumeMl(),
                String.format("%.2f", b.calcularPrecoFinal())
            });
        }

        tblBebidas.setModel(modelo);
        personalizarTabela();
    }
    private String identificarTipo(Bebida b) {
        if (b instanceof Vinho) {
            return "Vinho";
        } else if (b instanceof Suco) {
            return "Suco";
        } else if (b instanceof Espumante) {
            return "Espumante";
        } else {
            return "Bebida";
        }
    }
    
    private Bebida obterBebidaSelecionada() {
        int linha = tblBebidas.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma bebida na tabela.");
            return null;
        }

        String nome = tblBebidas.getValueAt(linha, 0).toString();

        return BDBebida.getInstancia().consultarBebidaPorNome(nome);
    }
    
