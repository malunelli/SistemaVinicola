    private Cliente obterClienteSelecionado() {
        int linha = tblClientes.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione um cliente na tabela.");
            return null;
        }

        String cpf = tblClientes.getValueAt(linha, 0).toString();

        return BDCliente.getInstancia().consultarClientePorCpf(cpf);
    }

    private void alterarCliente() {
        Cliente cliente = obterClienteSelecionado();

        if (cliente == null) {
            return;
        }

        FormCadastroCliente tela = FormCadastroCliente.getInstancia();
        tela.prepararParaEdicao(cliente);
        tela.setLocationRelativeTo(this);
        tela.setVisible(true);
    }

    private void excluirCliente() {
        Cliente cliente = obterClienteSelecionado();

        if (cliente == null) {
            return;
        }

        int opcao = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir o cliente " + cliente.getNome() + "?",
                "Confirmar exclusao",
                JOptionPane.YES_NO_OPTION
        );

        if (opcao == JOptionPane.YES_OPTION) {
            boolean excluiu = BDCliente.getInstancia().excluirCliente(cliente.getCpf());

            if (excluiu) {
                JOptionPane.showMessageDialog(this, "Cliente excluido com sucesso!");
                preencherTabela();
            } else {
                JOptionPane.showMessageDialog(this, "Cliente nao encontrado.");
            }
        }
    }

    private void mostrarDetalhes() {
        Cliente cliente = obterClienteSelecionado();

        if (cliente == null) {
            return;
        }

        String mensagem = "";

        mensagem += "CPF: " + cliente.getCpf() + "\n";
        mensagem += "Nome: " + cliente.getNome() + "\n";
        mensagem += "Resumo: " + cliente.gerarResumo() + "\n";
        mensagem += "Telefone: " + cliente.getTelefone() + "\n";
        mensagem += "Email: " + cliente.getEmail() + "\n";
        mensagem += "Data de Nascimento: " + cliente.getDataNascimento() + "\n";
        mensagem += "Endereco: " + cliente.getEnderecoEntrega() + "\n";
        mensagem += "Limite de Credito: R$ " + String.format("%.2f", cliente.getLimiteCredito()) + "\n";

        JOptionPane.showMessageDialog(this, mensagem, "Detalhes do Cliente", JOptionPane.INFORMATION_MESSAGE);
    }

    public void preencherTabela() {
        DefaultTableModel modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        modelo.addColumn("CPF");
        modelo.addColumn("Nome");
        modelo.addColumn("Telefone");
        modelo.addColumn("Limite de Credito");

        for (Cliente c : BDCliente.getInstancia().getClientes()) {
            modelo.addRow(new Object[]{
                c.getCpf(),
                c.getNome(),
                c.getTelefone(),
                String.format("%.2f", c.getLimiteCredito())
            });
        }

        tblClientes.setModel(modelo);
        personalizarTabela();
    }

    private void atualizar() {
        preencherTabela();
    }

