    public void preencherFormulario(Vendedor v) {
        txtCpf.setText(v.getCpf());
        txtCpf.setEditable(false);
        txtNome.setText(v.getNome());
        txtTelefone.setText(v.getTelefone());
        txtEmail.setText(v.getEmail());
        txtDataNasc.setText(v.getDataNascimento());
        txtMatricula.setText(v.getMatricula());
        txtSalario.setText(String.valueOf(v.getSalarioBase()));
        txtComissao.setText(String.valueOf(v.getPercentualComissao()));
    }

    public void prepararParaEdicao(Vendedor v) {
        vendedorEmEdicao = v;
        preencherFormulario(v);
    }

    private void salvarVendedor() {
        try {
            boolean estavaEditando = vendedorEmEdicao != null;

            String nome = txtNome.getText();
            String cpf = txtCpf.getText();
            String telefone = txtTelefone.getText();
            String email = txtEmail.getText();
            String dataNasc = txtDataNasc.getText();
            String matricula = txtMatricula.getText();
            double salario = Double.parseDouble(txtSalario.getText());
            double comissao = Double.parseDouble(txtComissao.getText());

            if (vendedorEmEdicao == null) {
                Vendedor vendedor = new Vendedor();

                vendedor.setCpf(cpf);
                vendedor.setNome(nome);
                vendedor.setTelefone(telefone);
                vendedor.setEmail(email);
                vendedor.setDataNascimento(dataNasc);
                vendedor.setMatricula(matricula);
                vendedor.setSalarioBase(salario);
                vendedor.setPercentualComissao(comissao);

                BDVendedor.getInstancia().adicionarVendedor(vendedor);

                JOptionPane.showMessageDialog(this, "Vendedor cadastrado com sucesso!");
            } else {
                vendedorEmEdicao.setNome(nome);
                vendedorEmEdicao.setTelefone(telefone);
                vendedorEmEdicao.setEmail(email);
                vendedorEmEdicao.setDataNascimento(dataNasc);
                vendedorEmEdicao.setMatricula(matricula);
                vendedorEmEdicao.setSalarioBase(salario);
                vendedorEmEdicao.setPercentualComissao(comissao);

                BDVendedor.getInstancia().alterarVendedor(cpf, vendedorEmEdicao);

                JOptionPane.showMessageDialog(this, "Vendedor alterado com sucesso!");
            }

            limparCampos();

            if (estavaEditando) {
                fechar();
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Erro: salário e comissão devem ser números válidos.");
        } catch (CpfInvalidoException e) {
            JOptionPane.showMessageDialog(this, "Erro no CPF: " + e.getMessage());
        } catch (SalarioInvalidoException e) {
            JOptionPane.showMessageDialog(this, "Erro no salário: " + e.getMessage());
        } catch (ComissaoInvalidaException e) {
            JOptionPane.showMessageDialog(this, "Erro na comissão: " + e.getMessage());
        }
    }

    public void limparCampos() {
        vendedorEmEdicao = null;

        txtCpf.setText("");
        txtCpf.setEditable(true);
        txtNome.setText("");
        txtTelefone.setText("");
        txtEmail.setText("");
        txtDataNasc.setText("");
        txtMatricula.setText("");
        txtSalario.setText("");
        txtComissao.setText("");

        txtCpf.requestFocus();
    }

    private void fechar() {
        this.dispose();
    }
