    private void personalizarMenu() {
        Color vinho = new Color(92, 24, 45);
        Color vinhoClaro = new Color(120, 40, 65);
        Color branco = new Color(255, 255, 255);
        Font fonteMenu = new Font("Segoe UI", Font.BOLD, 13);

        JMenuBar barra = getJMenuBar();

        if (barra != null) {
            barra.setOpaque(true);
            barra.setBackground(vinho);
            barra.setBorder(BorderFactory.createLineBorder(vinho));

            barra.setUI(new BasicMenuBarUI() {
                @Override
                public void paint(Graphics g, javax.swing.JComponent c) {
                    g.setColor(vinho);
                    g.fillRect(0, 0, c.getWidth(), c.getHeight());
                }
            });

            for (int i = 0; i < barra.getMenuCount(); i++) {
                JMenu menu = barra.getMenu(i);

                if (menu != null) {
                    menu.setOpaque(true);
                    menu.setBackground(vinho);
                    menu.setForeground(branco);
                    menu.setFont(fonteMenu);
                    menu.setBorderPainted(false);

                    menu.getPopupMenu().setBackground(vinho);
                    menu.getPopupMenu().setBorder(BorderFactory.createLineBorder(vinhoClaro));

                    for (int j = 0; j < menu.getItemCount(); j++) {
                        JMenuItem item = menu.getItem(j);

                        if (item != null) {
                            item.setOpaque(true);
                            item.setBackground(vinho);
                            item.setForeground(branco);
                            item.setFont(fonteMenu);
                        }
                    }
                }
            }
        }
    }
    
