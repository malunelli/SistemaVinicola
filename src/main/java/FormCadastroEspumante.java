    private void salvarEspumante() {
        try {
            String nome = txtNome.getText();
            if (BDBebida.getInstancia().consultarBebidaPorNome(nome) != null) {
                JOptionPane.showMessageDialog(this, "Ja existe uma bebida cadastrada com esse nome.");
                return;
            }
            int volume = Integer.parseInt(txtVolume.getText());
            double preco = Double.parseDouble(txtPreco.getText());
            String tipoFermentacao = txtTipoFermentacao.getText();
            double precoAdicionalBrut = Double.parseDouble(txtPrecoAdicionalBrut.getText());

            Espumante espumante = new Espumante();

            espumante.setNome(nome);
            espumante.setVolumeMl(volume);
            espumante.setPrecoBase(preco);
            espumante.setTipoFermentacao(tipoFermentacao);
            espumante.setPrecoAdicionalBrut(precoAdicionalBrut);

            BDBebida.getInstancia().adicionarBebida(espumante);

            JOptionPane.showMessageDialog(this, "Espumante cadastrado com sucesso!");

            limparCampos();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Erro: volume, preço e preço adicional devem ser números válidos.");
        } catch (PrecoInvalidoException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        } catch (VolumeInvalidoException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }

    public void limparCampos() {
        txtNome.setText("");
        txtVolume.setText("");
        txtPreco.setText("");
        txtTipoFermentacao.setText("");
        txtPrecoAdicionalBrut.setText("");
        txtNome.requestFocus();
    }

    private void fechar() {
        this.dispose();
    }
    
