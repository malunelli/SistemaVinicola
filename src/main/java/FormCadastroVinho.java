    private void salvarVinho() {
        try {
            String nome = txtNome.getText();
            if (BDBebida.getInstancia().consultarBebidaPorNome(nome) != null) {
                JOptionPane.showMessageDialog(this, "Ja existe uma bebida cadastrada com esse nome.");
                return;
            }
            int volume = Integer.parseInt(txtVolume.getText());
            double preco = Double.parseDouble(txtPreco.getText());
            String tipoUva = txtTipoUva.getText();
            int anoSafra = Integer.parseInt(txtAnoSafra.getText());
            

            Vinho vinho = new Vinho();

            vinho.setNome(nome);
            vinho.setVolumeMl(volume);
            vinho.setPrecoBase(preco);
            vinho.setTipoUva(tipoUva);
            vinho.setAnoSafra(anoSafra);

            BDBebida.getInstancia().adicionarBebida(vinho);

            JOptionPane.showMessageDialog(this, "Vinho cadastrado com sucesso!");

            limparCampos();

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Erro: volume, preço e ano da safra devem ser números válidos.");
        } catch (PrecoInvalidoException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        } catch (VolumeInvalidoException e) {
            JOptionPane.showMessageDialog(this, e.getMessage());
        }
    }
    
    public void limparCampos() {
        txtNome.setText("");
        txtVolume.setText("");
        txtPreco.setText("");
        txtTipoUva.setText("");
        txtAnoSafra.setText("");
        txtNome.requestFocus();
    }

