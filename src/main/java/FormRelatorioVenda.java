    public void preencherTabela() {
        DefaultTableModel modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        modelo.addColumn("Cliente");
        modelo.addColumn("Vendedor");
        modelo.addColumn("Bebida");
        modelo.addColumn("Quantidade");
        modelo.addColumn("Total");

        for (Venda v : BDVenda.getInstancia().getVendas()) {
            double total = v.calcularTotalVenda();

            modelo.addRow(new Object[]{
                v.getCliente().getNome(),
                v.getVendedor().getNome(),
                v.getBebidaVendida().getNome(),
                v.getQuantidade(),
                String.format("%.2f", total)
            });
        }

        tblVendas.setModel(modelo);
        personalizarTabela();
    }

    private Venda obterVendaSelecionada() {
        int linha = tblVendas.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma venda na tabela.");
            return null;
        }

        return BDVenda.getInstancia().consultarVendaPorIndice(linha);
    }

    private void mostrarDetalhes() {
        Venda v = obterVendaSelecionada();

        if (v == null) {
            return;
        }

        double total = v.calcularTotalVenda();
        double comissao = total * v.getVendedor().getPercentualComissao() / 100;

        String mensagem = "";

        mensagem += "Cliente: " + v.getCliente().getNome() + "\n";//Reflexividade
        mensagem += "CPF do Cliente: " + v.getCliente().getCpf() + "\n";
        mensagem += "Vendedor: " + v.getVendedor().getNome() + "\n";//Reflexividade
        mensagem += "Bebida: " + v.getBebidaVendida().getNome() + "\n";//Reflexividade
        mensagem += "Quantidade: " + v.getQuantidade() + "\n";
        mensagem += "Forma de Pagamento: " + v.getFormaPagamento() + "\n";
        mensagem += "Desconto: R$ " + String.format("%.2f", v.getDesconto()) + "\n";
        mensagem += "Total da Venda: R$ " + String.format("%.2f", total) + "\n";
        mensagem += "Comissao do Vendedor: R$ " + String.format("%.2f", comissao) + "\n";

        JOptionPane.showMessageDialog(this, mensagem, "Detalhes da Venda", JOptionPane.INFORMATION_MESSAGE);
    }

    private void excluirVenda() {
        int linha = tblVendas.getSelectedRow();

        if (linha == -1) {
            JOptionPane.showMessageDialog(this, "Selecione uma venda na tabela.");
            return;
        }

        int opcao = JOptionPane.showConfirmDialog(
                this,
                "Deseja realmente excluir esta venda?",
                "Confirmar exclusao",
                JOptionPane.YES_NO_OPTION
        );

        if (opcao == JOptionPane.YES_OPTION) {
            boolean excluiu = BDVenda.getInstancia().excluirVenda(linha);

            if (excluiu) {
                JOptionPane.showMessageDialog(this, "Venda excluida com sucesso!");
                preencherTabela();
            } else {
                JOptionPane.showMessageDialog(this, "Venda nao encontrada.");
            }
        }
    }

    private void atualizar() {
        preencherTabela();
    }

    private void fechar() {
        this.dispose();
    }
    
